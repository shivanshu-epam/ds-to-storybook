/**
 * Archetype "action" (Button): native <button>, behaviour from the WAI-ARIA button pattern.
 * Figma supplies the variant axes, sizes, states, slots, styles and copy.
 */
import { generateStyles, type RoleDef, type StyleModel } from '../styles.ts';
import { docsJson, forced, kebab, mdxPage, partAt, pascal, q, sampleText, type ComponentReport, type TemplateContext, type TemplateResult } from './common.ts';

const STATE_AXIS = /^(state|interaction)$/i;

export function actionTemplate(ctx: TemplateContext, name: string): TemplateResult {
  const set = ctx.sets.main;
  if (!set) throw new Error(`${name}: the action template needs a "main" component set`);
  const dir = `src/components/${name}`;

  const enumAxes = set.properties.filter((p) => p.type === 'VARIANT' && !STATE_AXIS.test(p.name));
  const stateAxis = set.properties.find((p) => p.type === 'VARIANT' && STATE_AXIS.test(p.name));
  const slotBooleans = set.properties.filter((p) => p.type === 'BOOLEAN' && /icon/i.test(p.name));
  const labelBoolean = set.properties.find((p) => p.type === 'BOOLEAN' && /label/i.test(p.name));
  const slotProp = (figma: string) => (/leading/i.test(figma) ? 'leadingIcon' : /trailing/i.test(figma) ? 'trailingIcon' : `${kebab(figma).replace(/^has-|-([a-z])/g, (_, c) => (c ? c.toUpperCase() : ''))}`);

  const axisProp = (figma: string) => kebab(figma).replace(/-([a-z])/g, (_, c) => c.toUpperCase());
  const value = (v: string) => kebab(v);

  // States: native selectors, forceable for static stories.
  const stateSel: Record<string, ReturnType<typeof forced> | null | 'skip'> = {};
  for (const s of stateAxis?.options ?? []) {
    const k = s.toLowerCase();
    if (/^(default|enabled|rest)$/.test(k)) stateSel[s] = null;
    else if (/hover/.test(k)) stateSel[s] = forced('hover', ':hover:not(:disabled)');
    else if (/press|active/.test(k)) stateSel[s] = forced('pressed', ':active:not(:disabled)');
    else if (/focus/.test(k)) stateSel[s] = forced('focus', ':focus-visible');
    else if (/disabled/.test(k)) stateSel[s] = { target: 'root', selector: ':disabled' };
    else stateSel[s] = 'skip';
  }

  const label = (v: Parameters<RoleDef['find']>[0]) => v.parts.find((p) => p.type === 'TEXT');
  const roles: RoleDef[] = [
    { role: 'root', kind: 'box', find: (v) => ({ style: v.style }), minHeight: true, display: 'inline-flex', hint: ['interactive'] },
    { role: 'label', kind: 'text', parent: 'root', find: (v) => { const p = label(v); return p ? { style: p.style, part: p } : undefined; } },
    ...slotBooleans.map<RoleDef>((b) => ({
      role: slotProp(b.name),
      kind: 'icon',
      parent: 'root',
      includeHidden: true,
      find: (v) => { const p = partAt(v, /leading/i.test(b.name) ? /leading/i : /trailing/i); return p ? { style: p.style, part: p } : undefined; },
    })),
  ];
  const model: StyleModel = {
    axes: enumAxes.map((a) => ({ figma: a.name, attr: kebab(a.name), values: Object.fromEntries((a.options ?? []).map((o) => [o, value(o)])) })),
    stateAxes: stateAxis ? [{ figma: stateAxis.name, states: stateSel }] : [],
    roles,
  };
  const styles = generateStyles(set.variants, model, ctx.resolver);

  const css = `/* Generated by ds-sync from Figma "${set.name}" (${set.nodeId}). Do not edit by hand. */
.root {
  display: inline-flex;
  align-items: center;
  justify-content: center;
  box-sizing: border-box;
  border: 0;
  margin: 0;
  cursor: pointer;
  white-space: nowrap;
  text-decoration: none;
  -webkit-tap-highlight-color: transparent;
}
.root:focus-visible { outline: none; }
.root:disabled { cursor: not-allowed; }
.label { display: inline-block; }
${roles.filter((r) => r.kind === 'icon').map((r) => `.${r.role} { display: inline-flex; flex: none; }`).join('\n')}

${styles.css}`;

  // Props
  const propLines: string[] = [];
  const mapping: ComponentReport['props'] = [];
  for (const a of enumAxes) {
    const p = axisProp(a.name);
    propLines.push(`  /** Figma: ${a.name}. Default ${value(String(a.default))}. */\n  ${p}?: ${(a.options ?? []).map((o) => q(value(o))).join(' | ')};`);
    mapping.push({ prop: p, figma: `${a.name} (variant)` });
  }
  for (const b of slotBooleans) {
    const p = slotProp(b.name);
    propLines.push(`  /** Figma: ${b.name}. An icon element, e.g. <Icon name="…" />. */\n  ${p}?: ReactNode;`);
    mapping.push({ prop: p, figma: `${b.name} (boolean)`, note: 'Slot: shown when an element is passed.' });
  }
  propLines.push(`  /** Figma: ${labelBoolean?.name ?? 'label text'}. The button label. */\n  children?: ReactNode;`);
  mapping.push({ prop: 'children', figma: labelBoolean ? `${labelBoolean.name} (boolean) + label text` : 'label text' });
  if (stateAxis) {
    for (const s of stateAxis.options ?? []) {
      const sel = stateSel[s];
      const native = sel && sel !== 'skip' ? /:is\((.*), \[data-force/.exec(sel.selector)?.[1] : undefined;
      mapping.push({ prop: sel === null ? '—' : sel === 'skip' ? '(not generated)' : /disabled/i.test(s) ? 'disabled' : `${native ?? sel?.selector ?? ''} (CSS)`, figma: `${stateAxis.name}=${s}` });
    }
  }

  const defaults = enumAxes.map((a) => `${axisProp(a.name)} = ${q(value(String(a.default)))}`).join(', ');
  const dataAttrs = enumAxes.map((a) => `data-${kebab(a.name)}={${axisProp(a.name)}}`).join(' ');
  const slots = slotBooleans.map((b) => slotProp(b.name));
  const tsx = `// Generated by ds-sync from Figma "${set.name}" (${set.nodeId}). Do not edit by hand.
import type { ButtonHTMLAttributes, ReactNode } from 'react';

import styles from './${name}.module.css';

export interface ${name}Props extends ButtonHTMLAttributes<HTMLButtonElement> {
${propLines.join('\n')}
  /** Renders a pseudo state statically for docs and visual tests: "hover", "pressed" or "focus". */
  'data-force-state'?: string;
}

export function ${name}({ ${defaults}, ${slots.join(', ')}${slots.length ? ', ' : ''}type = 'button', className, children, ...rest }: ${name}Props) {
  return (
    <button type={type} className={[styles.root, className].filter(Boolean).join(' ')} ${dataAttrs} {...rest}>
${slots.includes('leadingIcon') ? `      {leadingIcon && <span className={styles.leadingIcon} aria-hidden="true">{leadingIcon}</span>}\n` : ''}      {children !== undefined && children !== null && <span className={styles.label}>{children}</span>}
${slots.includes('trailingIcon') ? `      {trailingIcon && <span className={styles.trailingIcon} aria-hidden="true">{trailingIcon}</span>}\n` : ''}    </button>
  );
}
`;

  // Stories
  const labelText = set.variants.map((v) => v.parts.find((p) => p.type === 'TEXT')?.text).find(Boolean) ?? name;
  const [rowAxis, ...otherAxes] = enumAxes;
  const stateArgs = (s: string) => {
    const sel = stateSel[s];
    if (sel === null) return '{}';
    if (/disabled/i.test(s)) return '{ disabled: true }';
    const m = sel && sel !== 'skip' ? /data-force-state~="(\w+)"/.exec(sel.selector)?.[1] : undefined;
    return m ? `{ 'data-force-state': '${m}' }` : '{}';
  };
  const statesForGrid = (stateAxis?.options ?? []).filter((s) => stateSel[s] !== 'skip');
  const iconNames = slotBooleans.map((b) => set.variants.map((v) => partAt(v, /leading/i.test(b.name) ? /leading/i : /trailing/i)?.instanceOf).find(Boolean));
  const iconImports = iconNames.filter(Boolean).map((n) => ctx.icons.get(n!)?.name).filter(Boolean) as string[];
  const argTypes = [
    ...enumAxes.map((a) => `    ${axisProp(a.name)}: { control: 'inline-radio', options: [${(a.options ?? []).map((o) => q(value(o))).join(', ')}], description: 'Figma: ${a.name}' },`),
    ...slots.map((s) => `    ${s}: { control: false, description: 'Figma: ${slotBooleans.find((b) => slotProp(b.name) === s)?.name}' },`),
    `    children: { control: 'text', description: 'Figma: label text' },`,
    `    'data-force-state': { table: { disable: true } },`,
  ];
  const storyExports: string[] = [];
  storyExports.push(`/** Figma default variant: ${enumAxes.map((a) => `${a.name}=${a.default}`).join(', ')}. */
export const Default: Story = {
  play: async ({ canvas, args }) => {
    await userEvent.click(canvas.getByRole('button', { name: ${q(labelText)} }));
    await expect(args.onClick).toHaveBeenCalledTimes(1);
  },
};`);
  if (rowAxis && stateAxis) {
    storyExports.push(`/** Figma Style grid: ${rowAxis.name} × ${stateAxis.name}. Pseudo states are forced with data-force-state. */
export const ${pascal(rowAxis.name)}sAndStates: Story = {
  parameters: { controls: { disable: true } },
  render: (args) => (
    <Matrix
      label="${rowAxis.name} by ${stateAxis.name}"
      columns={[${statesForGrid.map((s) => q(s)).join(', ')}]}
      rows={[${(rowAxis.options ?? []).map((o) => q(o)).join(', ')}]}
      cell={(row, column) => <${name} {...args} ${axisProp(rowAxis.name)}={ROW_VALUES[row]} {...STATE_ARGS[column]} />}
    />
  ),
};`);
  }
  for (const axis of otherAxes) {
    storyExports.push(`/** Figma ${axis.name} axis. */
export const ${pascal(axis.name)}: Story = {
  parameters: { controls: { disable: true } },
  render: (args) => (
    <Row>
${(axis.options ?? []).map((o) => `      <Labelled label=${q(o)}><${name} {...args} ${axisProp(axis.name)}=${q(value(o))} /></Labelled>`).join('\n')}
    </Row>
  ),
};`);
  }
  if (slots.length && iconImports.length) {
    storyExports.push(`/** Figma boolean slots: ${slotBooleans.map((b) => b.name).join(', ')}. Icons are the Figma defaults. */
export const WithIcons: Story = {
  parameters: { controls: { disable: true } },
  render: (args) => (
    <Row>
${slots.map((s, i) => (iconImports[i] ? `      <Labelled label=${q(slotBooleans[i]!.name)}><${name} {...args} ${s}={<Icon name="${iconImports[i]}" />} /></Labelled>` : '')).filter(Boolean).join('\n')}
    </Row>
  ),
};`);
  }
  if (statesForGrid.some((s) => /disabled/i.test(s))) {
    storyExports.push(`/** ${stateAxis!.name}=Disabled: clicks are ignored. */
export const Disabled: Story = {
  args: { disabled: true },
  play: async ({ canvas, args }) => {
    const button = canvas.getByRole('button');
    await expect(button).toBeDisabled();
    await userEvent.click(button, { pointerEventsCheck: 0 });
    await expect(args.onClick).not.toHaveBeenCalled();
  },
};`);
  }
  storyExports.push(`/** WAI-ARIA button pattern: Tab focuses; Enter and Space activate. */
export const Keyboard: Story = {
  play: async ({ canvas, args }) => {
    const button = canvas.getByRole('button');
    await userEvent.tab();
    await expect(button).toHaveFocus();
    await userEvent.keyboard('{Enter}');
    await userEvent.keyboard(' ');
    await expect(args.onClick).toHaveBeenCalledTimes(2);
  },
};`);

  const stories = `// Generated by ds-sync from Figma "${set.name}" (${set.nodeId}). Do not edit by hand.
import type { Meta, StoryObj } from '@storybook/react-vite';
import { expect, fn, userEvent } from 'storybook/test';

${iconImports.length ? `import { Icon } from '../../icons/Icon';\n` : ''}import { Labelled, Matrix, Row } from '../../storybook/layout';
import { ${name} } from './${name}';

${rowAxis ? `const ROW_VALUES: Record<string, ${name}Props['${axisProp(rowAxis.name)}']> = { ${(rowAxis.options ?? []).map((o) => `${q(o)}: ${q(value(o))}`).join(', ')} };\n` : ''}const STATE_ARGS: Record<string, Partial<${name}Props>> = { ${statesForGrid.map((s) => `${q(s)}: ${stateArgs(s)}`).join(', ')} };

const meta = {
  title: 'Components/${name}',
  component: ${name},
  args: { ${enumAxes.map((a) => `${axisProp(a.name)}: ${q(value(String(a.default)))}`).join(', ')}, children: ${q(labelText)}, onClick: fn() },
  argTypes: {
${argTypes.join('\n')}
  },
  parameters: { figma: { fileKey: ${q(ctx.fileKey)}, nodeId: ${q(set.nodeId)} } },
} satisfies Meta<typeof ${name}>;

export default meta;
type Story = StoryObj<typeof meta>;

${storyExports.join('\n\n')}
`.replace(`import { ${name} } from './${name}';`, `import { ${name}, type ${name}Props } from './${name}';`);

  const sections = [
    ...(rowAxis && stateAxis ? [{ heading: 'Variants and states', story: `${pascal(rowAxis.name)}sAndStates` }] : []),
    ...otherAxes.map((a) => ({ heading: a.name, story: pascal(a.name) })),
    ...(slots.length && iconImports.length ? [{ heading: 'Icons', story: 'WithIcons' }] : []),
  ];
  const description = set.description || sampleText(set, /description/i) || '';
  const files = [
    { path: `${dir}/${name}.tsx`, content: tsx },
    { path: `${dir}/${name}.module.css`, content: css },
    { path: `${dir}/${name}.stories.tsx`, content: stories },
    { path: `${dir}/${name}.mdx`, content: mdxPage(name, name, sections) },
    { path: `${dir}/${name}.figma.json`, content: docsJson(ctx, [set], name, description, mapping) },
  ];
  return {
    files,
    report: {
      name,
      figmaSets: [`${set.name} (${set.nodeId})`],
      files: files.map((f) => f.path),
      props: mapping,
      assumptions: [
        'Keyboard behaviour (Enter and Space activate) comes from the WAI-ARIA button pattern, not from Figma.',
        'Figma strokes are rendered as box-shadow so they do not change layout (inside, outside and centre alignment kept).',
        `Icon-only buttons are not generated: Figma "${labelBoolean?.name ?? 'Show label'}" off needs an accessible-name decision (aria-label).`,
      ],
      gaps: (stateAxis?.options ?? []).filter((s) => stateSel[s] === 'skip').map((s) => `State "${s}" has no selector mapping and was not generated.`),
      dependencies: styles.dependencies,
    },
  };
}
