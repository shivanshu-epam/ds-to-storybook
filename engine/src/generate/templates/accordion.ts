/**
 * Archetype "disclosure" (Accordion + AccordionItem): heading > button[aria-expanded] + region,
 * behaviour from the WAI-ARIA accordion pattern. Figma supplies the item set (Style × State).
 */
import { generateStyles, type RoleDef, type StateAxis, type StyleModel } from '../styles.ts';
import { axisDefault, axisOptions, docsJson, forced, kebab, mdxPage, partAt, q, sampleText, type ComponentReport, type TemplateContext, type TemplateResult } from './common.ts';

const part = (test: RegExp, extra: Partial<RoleDef> & Pick<RoleDef, 'role' | 'kind'>): RoleDef => ({
  ...extra,
  find: (v) => {
    const p = partAt(v, test);
    return p ? { style: p.style, part: p } : undefined;
  },
});

export function accordionTemplate(ctx: TemplateContext, name: string): TemplateResult {
  const set = ctx.sets.item;
  if (!set) throw new Error(`${name}: the accordion template needs an "item" component set`);
  const dir = `src/components/${name}`;
  const item = `${name}Item`;
  const styleAxis = set.properties.find((p) => p.type === 'VARIANT' && /^(style|variant|type)$/i.test(p.name));
  const stateAxisName = set.properties.find((p) => p.type === 'VARIANT' && /^state$/i.test(p.name))?.name ?? 'State';

  const state: StateAxis = { figma: stateAxisName, states: {} };
  for (const s of axisOptions(set, stateAxisName)) {
    const k = s.toLowerCase();
    state.states[s] = /default|enabled/.test(k) ? null
      : /hover/.test(k) ? forced('hover', ':hover:not(:disabled)', 'header')
      : /focus/.test(k) ? forced('focus', ':focus-visible', 'header')
      : /expanded|open/.test(k) ? { target: 'root', selector: '[data-state="open"]' }
      : /disabled/.test(k) ? { target: 'root', selector: '[data-disabled]' }
      : 'skip';
  }
  const model: StyleModel = {
    rootClass: 'item',
    axes: styleAxis ? [{ figma: styleAxis.name, attr: 'variant', values: Object.fromEntries((styleAxis.options ?? []).map((o) => [o, kebab(o)])) }] : [],
    stateAxes: [state],
    roles: [
      { role: 'root', kind: 'box', find: (v) => ({ style: v.style }) },
      part(/^_header$/, { role: 'header', kind: 'box', parent: 'root' }),
      part(/^_header\/_label$/, { role: 'label', kind: 'text', parent: 'header' }),
      part(/^_header\/_chevron$/, { role: 'chevron', kind: 'icon', parent: 'header' }),
      part(/^_panel$/, { role: 'panel', kind: 'box', parent: 'root', presence: true }),
      part(/^_panel\/_body$/, { role: 'body', kind: 'text', parent: 'panel' }),
    ],
  };
  const styles = generateStyles(set.variants, model, ctx.resolver);
  const chevronFigma = set.variants.map((v) => partAt(v, /_chevron$/)?.instanceOf).find(Boolean);
  const chevron = chevronFigma ? ctx.icons.get(chevronFigma)?.name : undefined;
  const variants = (styleAxis?.options ?? []).map(kebab);
  const defaultVariant = styleAxis ? kebab(String(styleAxis.default)) : undefined;

  const css = `/* Generated by ds-sync from Figma "${set.name}" (${set.nodeId}). Do not edit by hand. */
.accordion { display: flex; flex-direction: column; width: 100%; align-self: stretch; }
.item { display: flex; flex-direction: column; box-sizing: border-box; }
.heading { margin: 0; font: inherit; }
.header { display: flex; align-items: center; width: 100%; box-sizing: border-box; border: 0; margin: 0; text-align: start; cursor: pointer; font: inherit; }
.header:focus-visible { outline: none; }
.header:disabled { cursor: not-allowed; }
.label { flex: 1 1 auto; }
.chevron { display: inline-flex; flex: none; }
.panel { box-sizing: border-box; }
.panel[hidden] { display: none; }

${styles.css}`;

  const tsx = `// Generated by ds-sync from Figma "${set.name}" (${set.nodeId}). Do not edit by hand.
import { createContext, useContext, useId, useRef, useState, type KeyboardEvent, type ReactNode } from 'react';

${chevron ? `import { Icon } from '../../icons/Icon';\n` : ''}import styles from './${name}.module.css';

interface Ctx {
  isOpen: (value: string) => boolean;
  toggle: (value: string) => void;
  variant?: string;
  headingLevel: 2 | 3 | 4 | 5 | 6;
}

const AccordionContext = createContext<Ctx | null>(null);

export interface ${name}Props {
${styleAxis ? `  /** Figma: ${set.name} ${styleAxis.name}. Default ${defaultVariant}. */\n  variant?: ${variants.map(q).join(' | ')};\n` : ''}  /** Figma docs: single- or multiple-expand. Default single (one panel open at a time). */
  expandMode?: 'single' | 'multiple';
  /** Heading level wrapping each trigger. Not specified in Figma; default 3. */
  headingLevel?: 2 | 3 | 4 | 5 | 6;
  /** Open items (controlled). */
  value?: string[];
  /** Initially open items (uncontrolled). */
  defaultValue?: string[];
  onValueChange?: (value: string[]) => void;
  children: ReactNode;
  className?: string;
}

export function ${name}({ ${styleAxis ? `variant = ${q(defaultVariant!)}, ` : ''}expandMode = 'single', headingLevel = 3, value, defaultValue, onValueChange, children, className }: ${name}Props) {
  const [inner, setInner] = useState<string[]>(defaultValue ?? []);
  const open = value ?? inner;
  const ref = useRef<HTMLDivElement>(null);
  const toggle = (v: string) => {
    const next = open.includes(v) ? open.filter((x) => x !== v) : expandMode === 'single' ? [v] : [...open, v];
    if (value === undefined) setInner(next);
    onValueChange?.(next);
  };
  // WAI-ARIA accordion: ArrowDown/ArrowUp move between headers, Home/End jump to the ends. Disabled headers are skipped.
  const onKeyDown = (e: KeyboardEvent<HTMLDivElement>) => {
    const headers = Array.from(ref.current?.querySelectorAll<HTMLButtonElement>(\`.\${styles.header}:not(:disabled)\`) ?? []);
    const i = headers.indexOf(document.activeElement as HTMLButtonElement);
    if (i < 0) return;
    const target = { ArrowDown: (i + 1) % headers.length, ArrowUp: (i - 1 + headers.length) % headers.length, Home: 0, End: headers.length - 1 }[e.key];
    if (target === undefined) return;
    e.preventDefault();
    headers[target]?.focus();
  };
  return (
    <AccordionContext.Provider value={{ isOpen: (v) => open.includes(v), toggle, ${styleAxis ? 'variant, ' : ''}headingLevel }}>
      <div ref={ref} className={[styles.accordion, className].filter(Boolean).join(' ')} onKeyDown={onKeyDown}>
        {children}
      </div>
    </AccordionContext.Provider>
  );
}

export interface ${item}Props {
  /** Identifies the item in value / defaultValue. */
  value: string;
  /** Figma: header label. */
  title: ReactNode;
  /** Figma: ${stateAxisName}=Disabled. */
  disabled?: boolean;
  /** Figma: panel body. */
  children: ReactNode;
  /** Renders a pseudo state statically for docs and visual tests: "hover" or "focus". */
  'data-force-state'?: string;
}

export function ${item}({ value, title, disabled, children, 'data-force-state': forceState }: ${item}Props) {
  const ctx = useContext(AccordionContext);
  if (!ctx) throw new Error('${item} must be used inside ${name}');
  const id = useId();
  const open = ctx.isOpen(value);
  const Heading = \`h\${ctx.headingLevel}\` as const;
  return (
    <div className={styles.item} data-variant={ctx.variant} data-state={open ? 'open' : 'closed'} data-disabled={disabled ? '' : undefined}>
      <Heading className={styles.heading}>
        <button
          type="button"
          id={\`\${id}-header\`}
          className={styles.header}
          aria-expanded={open}
          aria-controls={\`\${id}-panel\`}
          disabled={disabled}
          data-force-state={forceState}
          onClick={() => ctx.toggle(value)}
        >
          <span className={styles.label}>{title}</span>
${chevron ? `          <span className={styles.chevron} aria-hidden="true"><Icon name="${chevron}" /></span>\n` : ''}        </button>
      </Heading>
      <div id={\`\${id}-panel\`} role="region" aria-labelledby={\`\${id}-header\`} className={styles.panel} hidden={!open}>
        <div className={styles.body}>{children}</div>
      </div>
    </div>
  );
}
`;

  const title = sampleText(set, /_header\/_label$/) ?? 'Section';
  const body = sampleText(set, /_panel\/_body$/) ?? '';
  const width = Math.round(set.variants[0]?.style.width ?? 360);
  const stateList = axisOptions(set, stateAxisName);
  const stateCell = (s: string, i: number) => {
    const k = s.toLowerCase();
    const props = /hover/.test(k) ? ` data-force-state="hover"` : /focus/.test(k) ? ` data-force-state="focus"` : /disabled/.test(k) ? ' disabled' : '';
    return `      <Labelled label=${q(s)}>\n        <${name} {...args}${/expanded|open/.test(k) ? ` defaultValue={['s${i}']}` : ''}>\n          <${item} value="s${i}" title={t(${i + 1})}${props}>{BODY}</${item}>\n        </${name}>\n      </Labelled>`;
  };
  const stories = `// Generated by ds-sync from Figma "${set.name}" (${set.nodeId}). Do not edit by hand.
import type { Meta, StoryObj } from '@storybook/react-vite';
import { expect, userEvent } from 'storybook/test';

import { Labelled, Stack } from '../../storybook/layout';
import { ${name}, ${item} } from './${name}';

/** Figma sample copy from the ${set.name} variants. Titles get a number so open panels have distinct names (axe landmark-unique). */
const TITLE = ${q(title)};
const BODY = ${q(body)};
const t = (n: number) => \`\${TITLE} \${n}\`;

const meta = {
  title: 'Components/${name}',
  component: ${name},
  args: { ${styleAxis ? `variant: ${q(defaultVariant!)}, ` : ''}expandMode: 'single', headingLevel: 3, children: null },
  argTypes: {
${styleAxis ? `    variant: { control: 'inline-radio', options: [${variants.map(q).join(', ')}], description: 'Figma: ${styleAxis.name}' },\n` : ''}    expandMode: { control: 'inline-radio', options: ['single', 'multiple'], description: 'Figma docs: single- or multiple-expand' },
    headingLevel: { control: 'inline-radio', options: [2, 3, 4, 5, 6], description: 'Not in Figma (archetype default 3)' },
    children: { table: { disable: true } },
  },
  decorators: [(Story) => <div style={{ width: ${width}, maxWidth: '100%' }}><Story /></div>],
  parameters: { figma: { fileKey: ${q(ctx.fileKey)}, nodeId: ${q(set.nodeId)} } },
} satisfies Meta<typeof ${name}>;

export default meta;
type Story = StoryObj<typeof meta>;

/** Three items with the Figma sample copy. Clicking a header opens its panel. */
export const Default: Story = {
  render: (args) => (
    <${name} {...args}>
      <${item} value="one" title={t(1)}>{BODY}</${item}>
      <${item} value="two" title={t(2)}>{BODY}</${item}>
      <${item} value="three" title={t(3)}>{BODY}</${item}>
    </${name}>
  ),
  play: async ({ canvas }) => {
    const [first] = canvas.getAllByRole('button');
    await expect(first).toHaveAttribute('aria-expanded', 'false');
    await userEvent.click(first!);
    await expect(first).toHaveAttribute('aria-expanded', 'true');
    await expect(canvas.getByRole('region')).toBeVisible();
  },
};

/** Single-expand: opening one item closes the other. */
export const SingleExpand: Story = {
  args: { expandMode: 'single' },
  render: (args) => (
    <${name} {...args}>
      <${item} value="one" title={t(1)}>{BODY}</${item}>
      <${item} value="two" title={t(2)}>{BODY}</${item}>
    </${name}>
  ),
  play: async ({ canvas }) => {
    const [a, b] = canvas.getAllByRole('button');
    await userEvent.click(a!);
    await userEvent.click(b!);
    await expect(a).toHaveAttribute('aria-expanded', 'false');
    await expect(b).toHaveAttribute('aria-expanded', 'true');
  },
};

/** Multiple-expand: items open independently. */
export const MultipleExpand: Story = {
  args: { expandMode: 'multiple' },
  render: SingleExpand.render,
  play: async ({ canvas }) => {
    const [a, b] = canvas.getAllByRole('button');
    await userEvent.click(a!);
    await userEvent.click(b!);
    await expect(a).toHaveAttribute('aria-expanded', 'true');
    await expect(b).toHaveAttribute('aria-expanded', 'true');
  },
};
${styleAxis ? `
/** Figma ${styleAxis.name}: ${(styleAxis.options ?? []).join(', ')}. */
export const Styles: Story = {
  parameters: { controls: { disable: true } },
  render: (args) => (
    <Stack>
${(styleAxis.options ?? []).map((o, i) => `      <Labelled label=${q(o)}>\n        <${name} {...args} variant=${q(kebab(o))} defaultValue={['v${i}']}>\n          <${item} value="v${i}" title={t(${i * 2 + 1})}>{BODY}</${item}>\n          <${item} value="w${i}" title={t(${i * 2 + 2})}>{BODY}</${item}>\n        </${name}>\n      </Labelled>`).join('\n')}
    </Stack>
  ),
};
` : ''}
/** Figma ${stateAxisName} axis. Pseudo states are forced with data-force-state. */
export const States: Story = {
  parameters: { controls: { disable: true } },
  render: (args) => (
    <Stack>
${stateList.map(stateCell).join('\n')}
    </Stack>
  ),
};

/** WAI-ARIA accordion keyboard: Enter and Space toggle; ArrowDown, ArrowUp, Home and End move focus. */
export const Keyboard: Story = {
  render: (args) => (
    <${name} {...args}>
      <${item} value="one" title={t(1)}>{BODY}</${item}>
      <${item} value="two" title={t(2)}>{BODY}</${item}>
      <${item} value="three" title={t(3)}>{BODY}</${item}>
    </${name}>
  ),
  play: async ({ canvas }) => {
    const [a, b, c] = canvas.getAllByRole('button');
    await userEvent.tab();
    await expect(a).toHaveFocus();
    await userEvent.keyboard('{ArrowDown}');
    await expect(b).toHaveFocus();
    await userEvent.keyboard('{End}');
    await expect(c).toHaveFocus();
    await userEvent.keyboard('{Home}');
    await expect(a).toHaveFocus();
    await userEvent.keyboard('{Enter}');
    await expect(a).toHaveAttribute('aria-expanded', 'true');
    await userEvent.keyboard(' ');
    await expect(a).toHaveAttribute('aria-expanded', 'false');
  },
};
`;

  const mapping: ComponentReport['props'] = [
    ...(styleAxis ? [{ prop: 'variant', figma: `${styleAxis.name} (variant)` }] : []),
    { prop: 'value / defaultValue', figma: `${stateAxisName}=Expanded` },
    { prop: `${item} disabled`, figma: `${stateAxisName}=Disabled` },
    { prop: `${item} title`, figma: 'header label text' },
    { prop: 'expandMode', figma: 'Figma docs (single / multiple expand)' },
    { prop: 'headingLevel', figma: '— (not in Figma)', note: 'Archetype default 3.' },
  ];
  const files = [
    { path: `${dir}/${name}.tsx`, content: tsx },
    { path: `${dir}/${name}.module.css`, content: css },
    { path: `${dir}/${name}.stories.tsx`, content: stories },
    {
      path: `${dir}/${name}.mdx`,
      content: mdxPage(name, name, [
        ...(styleAxis ? [{ heading: 'Styles', story: 'Styles' }] : []),
        { heading: 'States', story: 'States' },
        { heading: 'Single and multiple expand', story: 'MultipleExpand' },
      ]),
    },
    { path: `${dir}/${name}.figma.json`, content: docsJson(ctx, [set], name, set.description, mapping) },
  ];
  return {
    files,
    report: {
      name,
      figmaSets: [`${set.name} (${set.nodeId})`],
      files: files.map((f) => f.path),
      props: mapping,
      assumptions: [
        'Keyboard behaviour (Enter/Space toggle, arrows, Home, End) comes from the WAI-ARIA accordion pattern.',
        'Heading level is not specified in Figma; default h3.',
        `Item width ${width}px is the Figma item width, applied in stories only; the component fills its container.`,
        'Spacing between items is not in the item set; items stack with no gap.',
        'Story titles reuse the one Figma sample title with a number appended, so open panels have distinct accessible names.',
      ],
      gaps: [],
      dependencies: styles.dependencies,
    },
  };
}
